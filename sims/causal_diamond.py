"""Background-free toy model (idea 001): a finite 1+1 causal diamond.

Points are generated by Poisson sprinkling (stand-in for unknown dynamics, as in causal set theory),
then coordinates are forgotten: every observable below uses only the order relation
  i < j  <=>  u_i < u_j and v_i < v_j      (light-cone coordinates u, v in [0,1]).

(1) Proper time from counting: the longest chain between the diamond's tips.
    In 1+1 the sprinkled diamond is a random permutation, so the longest chain is the
    longest increasing subsequence (Ulam's problem): mean ~ 2 sqrt(n), fluctuations ~ n^(1/6).
(2) Neighbours: number of future links of the most central element. The links are the minimal
    elements of its future; sorted by u they are the running minima ("records") of v, so for m points
    in its future the expected number is the harmonic number H_m = 1 + 1/2 + ... + 1/m ~ ln m + 0.577.
"""
import bisect
import numpy as np

rng = np.random.default_rng(20261024)

def longest_chain(u, v):
    order = np.argsort(u)
    tails = []
    for y in v[order]:
        k = bisect.bisect_left(tails, y)
        if k == len(tails):
            tails.append(y)
        else:
            tails[k] = y
    return len(tails)

def central_links(u, v):
    # an extra element placed at the centre (choosing the "most central" sprinkled point biases the count)
    fut = (u > 0.5) & (v > 0.5)
    vf = v[fut][np.argsort(u[fut])]
    records = np.sum(vf == np.minimum.accumulate(vf)) if vf.size else 0
    return int(records), int(fut.sum())

if __name__ == "__main__":
    print("(1) longest chain L in a diamond with n points (proper time from counting)")
    print("        n     <L>    2sqrt(n)   <L>/2sqrt(n)   std(L)   std/n^(1/6)   std/<L>")
    for n in [100, 1_000, 10_000, 100_000]:
        trials = 400 if n <= 10_000 else 100
        Ls = np.array([longest_chain(rng.random(n), rng.random(n)) for _ in range(trials)])
        print(f"  {n:>7}  {Ls.mean():7.1f}  {2*np.sqrt(n):8.1f}     {Ls.mean()/(2*np.sqrt(n)):.3f}        "
              f"{Ls.std():6.2f}     {Ls.std()/n**(1/6):.3f}        {Ls.std()/Ls.mean():.4f}")

    print("\n(2) future links of the central element (m = points in its future)")
    print("          n   <links>   <H_m>    ln(n)")
    for n in [100, 1_000, 10_000, 100_000, 1_000_000]:
        trials = 2000 if n <= 10_000 else 200
        res = [central_links(rng.random(n), rng.random(n)) for _ in range(trials)]
        links = np.mean([r[0] for r in res])
        H = np.mean([np.sum(1 / np.arange(1, r[1] + 1)) for r in res])
        print(f"  {n:>9}  {links:7.2f}  {H:7.2f}  {np.log(n):6.2f}")
